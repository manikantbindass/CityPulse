export type DistrictInput = {
  id: string;
  city: string;
  name: string;
  category: string;
  demand?: number | null;
  availability?: number | null;
  forecastDemand?: number | null;
  seasonalBaseline?: number | null;
  receivingCapacity?: number;
  minimumCoverage?: number;
  priority?: number;
  risk?: number;
  accessibility?: number | null;
  businessesPerKm2?: number | null;
  latitude?: number | null;
  longitude?: number | null;
  evidence?: string[];
};
export type ScenarioInput = {
  name: string;
  origin: 'synthetic' | 'manual-assumptions' | 'authorized-snapshot';
  dataMode: 'synthetic' | 'assumed' | 'historical' | 'live';
  useCase: 'retail' | 'logistics' | 'public-service';
  unit: 'count' | 'kg' | 'litre' | 'kwh' | 'trip';
  currency: string;
  timeZone: string;
  periodStart: string;
  periodEnd: string;
  budget: number;
  objective: 'balanced' | 'throughput' | 'cost' | 'coverage' | 'fairness';
  minimumCoverage?: number;
  demandMultiplier?: number;
  availabilityMultiplier?: number;
  demandBasis?: 'observed' | 'forecast';
  integral?: boolean;
  includeTradeoffs?: boolean;
  scoreWeights?: {
    gap: number;
    risk: number;
    accessibility: number;
    density: number;
    seasonality: number;
  };
  objectiveWeights?: { throughput: number; cost: number; fairness: number };
  densityReferencePerKm2?: number;
  snapshotId?: string | null;
  networkId?: string | null;
  maxTravelMinutes?: number | null;
  districts: DistrictInput[];
  stocks: {
    id: string;
    category: string;
    quantity: number;
    unitCost: number;
    name: string;
    evidence?: string[];
  }[];
  lanes?: {
    sourceId: string;
    districtId: string;
    unitCost: number;
    capacity: number;
    travelMinutes: number;
  }[];
};
export type Opportunity = DistrictInput & {
  effectiveDemand: number | null;
  effectiveAvailability: number | null;
  gap: number | null;
  ratio: number | null;
  score: number | null;
  seasonalChangeFraction: number | null;
  missingFeatures: string[];
  contributions: Record<string, { value: number; weight: number; points: number }>;
  interpretation: string;
};
export type Plan = {
  status: string;
  objective: string;
  diagnostics: string[];
  allocations: { sourceId: string; districtId: string; quantity: number; unitCost: number }[];
  districts?: { id: string; received: number; coverage: number; unmet: number }[];
  totalAllocated?: number;
  totalCost?: number;
  minimumCoverage?: number;
  remainingUnmet?: number;
  maxConstraintViolation?: number;
};
export type DecisionResult = {
  engineVersion: string;
  solver: string;
  scipyVersion: string;
  inputFingerprint: string;
  resultFingerprint: string;
  computeMs: number;
  canonicalInput: ScenarioInput;
  opportunities: Opportunity[];
  optimization: Plan;
  tradeoffs: Plan[];
  cityComparisons: {
    city: string;
    groupCount: number;
    scoredGroupCount: number;
    meanScore: number | null;
    knownGap: number;
    plannedAllocation: number;
    missingDistricts: number;
  }[];
  assumptions: Record<string, unknown>;
  limitations: string[];
};
export type DecisionRun = { id: string; persisted: boolean; result: DecisionResult };

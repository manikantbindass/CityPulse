#!/bin/sh
set -eu
: "${POSTGRES_PASSWORD:?}" "${DATABASE_PASSWORD:?}"
export PGPASSWORD="$POSTGRES_PASSWORD"
psql -h db -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 <<'SQL'
\getenv app_password DATABASE_PASSWORD
SELECT 'CREATE ROLE citypulse_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname='citypulse_app')\gexec
ALTER ROLE citypulse_app PASSWORD :'app_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO citypulse_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO citypulse_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO citypulse_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO citypulse_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO citypulse_app;
SQL
